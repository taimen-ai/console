/**
 * Generates the dependency part of THIRD_PARTY.md from the installed workspace.
 *
 *   node scripts/third-party.ts          # rewrite THIRD_PARTY.md below the marker
 *   node scripts/third-party.ts --check  # fail if THIRD_PARTY.md is out of date (CI)
 *
 * Source: `pnpm licenses list --prod --json` — production dependencies of every workspace
 * package, as pinned by pnpm-lock.yaml (run `pnpm install --frozen-lockfile` first). The text
 * above the marker (fonts, icons, notes) is written by hand and kept as is.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const MARKER = '<!-- generated-dependencies -->'
const FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'THIRD_PARTY.md')

/**
 * Packages offered under a choice of licences: the licence this project uses them under.
 * A new dual-licensed dependency fails generation until it is listed here.
 */
const ELECTED: Record<string, string> = {
  dompurify: 'Apache-2.0',
  jszip: 'MIT',
}

interface Entry { name: string, versions: string[], license: string }

const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
const byLicence = JSON.parse(raw) as Record<string, Entry[]>

const rows: { name: string, versions: string, license: string, elected?: string }[] = []
for (const [licence, entries] of Object.entries(byLicence)) {
  for (const e of entries) {
    if (e.name.startsWith('@console/')) continue
    const row = { name: e.name, versions: [...e.versions].sort().join(', '), license: e.license || licence }
    if (/\bOR\b/.test(row.license)) {
      const elected = ELECTED[e.name]
      if (elected === undefined) throw new Error(`${e.name}: dual licence ${row.license} — add the elected licence to ELECTED`)
      rows.push({ ...row, elected })
    } else {
      rows.push(row)
    }
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name, 'en'))

const line = (r: typeof rows[number]): string => `- ${r.name} ${r.versions} — ${r.license}${r.elected !== undefined ? ` (used under ${r.elected})` : ''}`
const dual = rows.filter(r => r.elected !== undefined)
const counts = new Map<string, number>()
for (const r of rows) counts.set(r.elected ?? r.license, (counts.get(r.elected ?? r.license) ?? 0) + 1)

const generated = [
  MARKER,
  '',
  '## Third-party npm dependencies',
  '',
  'Generated by `node scripts/third-party.ts` from `pnpm licenses list --prod --json`',
  '(production dependencies of all workspace packages, versions pinned by',
  '`pnpm-lock.yaml`); do not edit below the marker by hand. Development-only tools',
  '(TypeScript, Vite, Vitest, ESLint, Playwright, …) are not part of the delivery and are',
  'not listed. Licence names come from package metadata.',
  '',
  `Summary: ${rows.length} packages — ${[...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([l, n]) => `${l} ${n}`).join(', ')}.`,
  '',
  '### Components offered under a choice of licences',
  '',
  ...dual.map(line),
  '',
  '### All components',
  '',
  ...rows.map(line),
  '',
].join('\n')

const current = readFileSync(FILE, 'utf8')
const at = current.indexOf(MARKER)
if (at < 0) throw new Error(`THIRD_PARTY.md has no ${MARKER} marker`)
const next = current.slice(0, at) + generated

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('THIRD_PARTY.md is out of date: run `node scripts/third-party.ts` and commit the result')
    process.exit(1)
  }
  console.log(`THIRD_PARTY.md is up to date (${rows.length} packages)`)
} else {
  writeFileSync(FILE, next)
  console.log(`THIRD_PARTY.md: ${rows.length} packages`)
}
