/**
 * Экраны консоли на стенде: каждый открывается без ошибок в консоли браузера и без
 * серьёзных нарушений доступности (axe, WCAG 2.1 A/AA), основные действия доходят до ядра.
 */

const CONSOLE_ERRORS_ALLOWED = [/WebSocket/, /status of 401/]

async function openScreen(page: Page, path: string, heading: RegExp): Promise<string[]> {
  const errors: string[] = []
  page.on('console', (m) => { if (m.type() === 'error' && !CONSOLE_ERRORS_ALLOWED.some(r => r.test(m.text()))) errors.push(m.text()) })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(path)
  await expect(page.getByRole('heading', { level: 1, name: heading })).toBeVisible()
  return errors
}

async function axe(page: Page): Promise<void> {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  const serious = result.violations.filter(v => v.impact === 'serious' || v.impact === 'critical')
  expect(serious.map(v => `${v.id}: ${v.nodes.map(n => n.target.join(' ')).slice(0, 3).join(', ')}`)).toEqual([])
}

